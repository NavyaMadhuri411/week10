# Commented out IPython magic to ensure Python compatibility.

# Experiment 10: Chain-of-Thought Prompting for Math Reasoning

# %pip install -q -U google-genai

import re
import json
import time
from getpass import getpass
from google import genai
from google.genai import errors

# --------------------------------------------------
# STEP 1: API CONFIGURATION
# --------------------------------------------------

API_KEY = getpass("Enter your Gemini API key: ")
client = genai.Client(api_key=API_KEY)

MODEL = "gemini-3.8-flash"
TEMPERATURE = 0

# --------------------------------------------------
# STEP 2: DEFINE THE MATH PROBLEM
# --------------------------------------------------

problem = (
    "A farmer has 15 cows. He buys 7 more cows. "
    "Then he sells half of his cows. How many cows does he have left?"
)

# Same problem text in both prompts
direct_prompt = problem

cot_prompt = (
    problem
    + "\n\nLet's think step by step. Show each step, "
      "and then provide the final answer clearly."
)

# --------------------------------------------------
# STEP 3: CHECK MODEL AVAILABILITY
# --------------------------------------------------

def list_available_models():
    print("\nModels available for content generation:")
    try:
        for model_info in client.models.list():
            if "generateContent" in (
                model_info.supported_actions or []
            ):
                print(model_info.name)
    except Exception as e:
        print("Could not list models:", e)

# --------------------------------------------------
# STEP 4: SEND PROMPT WITH AUTOMATIC RETRIES
# --------------------------------------------------

def ask_llm(prompt, max_retries=5):
    for attempt in range(max_retries):
        try:
            response = client.models.generate_content(
                model=MODEL,
                contents=prompt,
                config={"temperature": TEMPERATURE}
            )
            if not response.text:
                raise RuntimeError("The model returned an empty response.")
            return response.text

        except errors.ServerError as e:
            if attempt == max_retries - 1:
                raise RuntimeError(
                    "Gemini server error persisted after retries."
                ) from e

            wait_seconds = 2 ** (attempt + 1)
            print(
                f"Temporary server error. Waiting {wait_seconds}s "
                f"before retry {attempt + 2}/{max_retries}..."
            )
            time.sleep(wait_seconds)

# --------------------------------------------------
# STEP 5: EXTRACT FINAL ANSWER
# --------------------------------------------------

def extract_answer(response_text):
    # Look for an explicitly labelled final answer first
    matches = re.findall(
        r"(?:final answer|answer)\s*[:\-]?\s*\**\s*(\d+)",
        response_text,
        flags=re.IGNORECASE
    )

    if matches:
        return int(matches[-1])

    # Otherwise, use the last number in the response
    numbers = re.findall(r"\b\d+\b", response_text)
    return int(numbers[-1]) if numbers else None

# --------------------------------------------------
# STEP 6: RUN DIRECT PROMPT
# --------------------------------------------------

direct_response = None
cot_response = None
direct_answer = None
cot_answer = None

print("\n=== DIRECT PROMPT ===")
print("Model:", MODEL)

try:
    direct_response = ask_llm(direct_prompt)
    direct_answer = extract_answer(direct_response)
    print(direct_response)
    print("Extracted answer:", direct_answer)

except Exception as e:
    print("Direct prompt failed:", e)
    if "404" in str(e) or "not found" in str(e).lower():
        list_available_models()

# --------------------------------------------------
# STEP 7: RUN CHAIN-OF-THOUGHT PROMPT
# --------------------------------------------------

print("\n=== CHAIN-OF-THOUGHT PROMPT ===")

try:
    cot_response = ask_llm(cot_prompt)
    cot_answer = extract_answer(cot_response)
    print(cot_response)
    print("Extracted answer:", cot_answer)

except Exception as e:
    print("CoT prompt failed:", e)
    if "404" in str(e) or "not found" in str(e).lower():
        list_available_models()

# --------------------------------------------------
# STEP 8: COMPARE ANSWERS
# --------------------------------------------------

expected_answer = 11

print("\n=== ANALYSIS ===")
print("Expected answer:", expected_answer)
print("Direct answer:", direct_answer)
print("CoT answer:", cot_answer)

if direct_answer is not None:
    print("Direct prompt correct:",
          direct_answer == expected_answer)
else:
    print("Direct prompt correct: Could not determine")

if cot_answer is not None:
    print("CoT prompt correct:",
          cot_answer == expected_answer)
else:
    print("CoT prompt correct: Could not determine")

if (
    direct_answer is not None
    and cot_answer is not None
):
    if (
        direct_answer == expected_answer
        and cot_answer == expected_answer
    ):
        print("Both prompts returned the correct answer.")
    elif cot_answer == expected_answer:
        print("CoT was correct; direct prompting was not.")
    elif direct_answer == expected_answer:
        print("Direct prompting was correct; CoT was not.")
    else:
        print("Neither prompt returned the expected answer.")
else:
    print("Comparison incomplete because one or both calls failed.")

# --------------------------------------------------
# STEP 9: SAVE RESULTS
# --------------------------------------------------

results = {
    "experiment": "Chain-of-Thought Prompting",
    "model": MODEL,
    "temperature": TEMPERATURE,
    "problem": problem,
    "expected_answer": expected_answer,
    "direct_response": direct_response,
    "direct_extracted_answer": direct_answer,
    "direct_correct": (
        direct_answer == expected_answer
        if direct_answer is not None else None
    ),
    "cot_response": cot_response,
    "cot_extracted_answer": cot_answer,
    "cot_correct": (
        cot_answer == expected_answer
        if cot_answer is not None else None
    )
}

with open("output.txt", "w", encoding="utf-8") as file:
    json.dump(results, file, indent=4, ensure_ascii=False)

print("\nResults saved to output.txt")

